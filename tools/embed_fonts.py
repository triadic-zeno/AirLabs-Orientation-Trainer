# Regenerates AirLabs/EmbeddedFonts.h from AirLabs/fonts/AirLabs-Inter-*.ttf.
# Run from the repository root:  python tools/embed_fonts.py
import os
root = os.path.join(os.path.dirname(__file__), '..', 'AirLabs')
fonts = [('AirLabs-Inter-Regular.ttf', 'kRegular'), ('AirLabs-Inter-SemiBold.ttf', 'kSemiBold'), ('AirLabs-Inter-Bold.ttf', 'kBold')]
out = ['// Generated by tools/embed_fonts.py from fonts/*.ttf: Inter (SIL Open Font License 1.1,',
       '// see fonts/OFL.txt), subset to Latin. Compiled into the DLL so the window font always',
       '// ships with the plugin; AirLabs writes these files to bakkesmod/data/fonts on load.',
       '#pragma once', '#include <cstddef>', '', 'namespace airlabs::fonts', '{']
for name, var in fonts:
    data = open(os.path.join(root, 'fonts', name), 'rb').read()
    out.append(f'    inline constexpr unsigned char {var}[{len(data)}] = {{')
    for i in range(0, len(data), 24):
        out.append('        ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
    out.append('    };')
out.append('    struct EmbeddedFont { const char* file; const unsigned char* data; std::size_t size; };')
out.append('    inline constexpr EmbeddedFont kAll[] = {')
for name, var in fonts:
    out.append(f'        {{ "{name}", {var}, sizeof({var}) }},')
out.append('    };')
out.append('}')
open(os.path.join(root, 'EmbeddedFonts.h'), 'w').write('\n'.join(out) + '\n')
print('wrote EmbeddedFonts.h')
