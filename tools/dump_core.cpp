// Writes the numbers the leaderboard server needs from AirLabs/TrainerCore.h (presets, run
// rules, scoring constants and Rocket League rank names) as a JavaScript module, so the server and the plugin
// can't drift apart. The deploy workflow rebuilds this and stops if server/src/core-data.js is stale.
// Build: g++ -std=c++20 -O1 -IAirLabs tools/dump_core.cpp -o dump_core && ./dump_core > server/src/core-data.js
#include <cstdio>
#include <string>
#include <vector>
struct Vector { float X, Y, Z; };
#include "TrainerCore.h"

using namespace airlabs;

static std::string Str(const char* s)
{
    std::string o = "\"";
    for (const char* p = s; *p; ++p) { if (*p == '"' || *p == '\\') o += '\\'; o += *p; }
    return o + "\"";
}
static std::string Num(double v)
{
    char b[64];
    std::snprintf(b, sizeof b, "%.9g", v);
    return b;
}

int main()
{
    std::printf("// Generated by tools/dump_core.cpp from AirLabs/TrainerCore.h. Don't edit by hand.\n");
    std::printf("export default {\n");
    std::printf("  \"constants\": {\n");
    struct { const char* k; double v; } c[] = {
        { "pitchTorque", kPitchTorque }, { "maxSpin", kMaxSpin }, { "parReaction", kParReaction }, { "parFactor", kParFactor },
        { "maxBallSpeed", kMaxBallSpeed }, { "presetHoldSec", kPresetHoldSec }, { "presetTimeout", kPresetTimeout },
        { "chaseTimeout", kChaseTimeout }, { "chaseHoldSec", kChaseHoldSec }, { "missPenalty", kMissPenalty },
        { "presetDelaySec", kPresetDelaySec }, { "presetRunSec", kPresetRunSec }, { "hybridTrackSec", kHybridTrackSec },
        { "hybridFlickMin", kHybridFlickMin }, { "hybridFlickMax", kHybridFlickMax }, { "chaseMoveMin", kChaseMoveMin },
        { "chaseMoveMax", kChaseMoveMax }, { "dynamicAccel", kDynamicAccel }, { "targetBallRadius", kTargetBallRadius },
    };
    for (std::size_t i = 0; i < std::size(c); ++i) std::printf("    %s: %s,\n", Str(c[i].k).c_str(), Num(c[i].v).c_str());
    std::printf("    \"rangeDistance\": [%s, %s, %s]\n  },\n", Num(kRangeDistance[0]).c_str(), Num(kRangeDistance[1]).c_str(), Num(kRangeDistance[2]).c_str());

    std::printf("  \"modes\": [\"Flick\", \"Track\", \"Hybrid\", \"Chase\"],\n");
    std::printf("  \"ranges\": [\"Short\", \"Medium\", \"Long\"],\n");
    std::printf("  \"flick\": [\n");
    for (int i = 0; i < PresetCount(kFlick); ++i)
    {
        const FlickPreset& p = kFlickPresets[i];
        std::printf("    { \"name\": %s, \"minTurn\": %s, \"maxTurn\": %s, \"aim\": %d, \"bandMin\": %s, \"bandMax\": %s, \"fixedDistance\": %s }%s\n",
                    Str(p.name).c_str(), Num(p.minTurn).c_str(), Num(p.maxTurn).c_str(), p.aim, Num(p.band.minDeg).c_str(), Num(p.band.maxDeg).c_str(),
                    Num(p.fixedDistance).c_str(), i + 1 < PresetCount(kFlick) ? "," : "");
    }
    std::printf("  ],\n");
    for (int mode : { kTrack, kHybrid, kChase })
    {
        std::printf("  %s: [\n", Str(mode == kTrack ? "track" : mode == kHybrid ? "hybrid" : "chase").c_str());
        for (int i = 0; i < PresetCount(mode); ++i)
        {
            const MovePreset& p = *MovePresetFor(mode, i);
            std::printf("    { \"name\": %s, \"group\": %s, \"dynamic\": %s, \"speed\": %s, \"vMin\": %s, \"vMax\": %s, \"changeEvery\": %s, \"maxTurn\": %s }%s\n",
                        Str(p.name).c_str(), Str(p.group).c_str(), p.dynamic ? "true" : "false", Num(p.speed).c_str(), Num(p.vMin).c_str(),
                        Num(p.vMax).c_str(), Num(p.changeEvery).c_str(), Num(p.maxTurn).c_str(), i + 1 < PresetCount(mode) ? "," : "");
        }
        std::printf("  ],\n");
    }

    std::printf("  \"tierNames\": [");
    for (int t = 0; t < kTierCount; ++t) std::printf("%s%s", Str(TierName(t)).c_str(), t + 1 < kTierCount ? ", " : "");
    std::printf("],\n  \"tierShort\": [");
    for (int t = 0; t < kTierCount; ++t) std::printf("%s%s", Str(TierShort(t)).c_str(), t + 1 < kTierCount ? ", " : "");
    std::printf("]\n");
    std::printf("};\n");
    return 0;
}
